# -- Copy the repository notebooks into the source tree --------------------
def _copy_notebooks(_app) -> None:
    """Mirror ``notebooks/*.ipynb`` into ``docs/examples/notebooks`` (gitignored)."""
    target = DOCS_DIR / "examples" / "notebooks"
    target.mkdir(parents=True, exist_ok=True)
    for notebook in (REPO_ROOT / "notebooks").glob("*.ipynb"):
        destination = target / notebook.name
        if not destination.exists() or destination.read_bytes() != notebook.read_bytes():
            shutil.copy2(notebook, destination)


def _short_dashes(app, doctree, docname) -> None:
    """Use the plain '-' everywhere: replace en/em dashes generated by Sphinx.

    Sphinx writes ``name (type) -- description`` in parameter lists and its
    smart-quotes step turns ``--`` into an en dash. Our own text never uses
    long dashes, so any left at this point were generated.
    """
    from docutils import nodes

    for text in list(doctree.findall(nodes.Text)):
        if "\u2013" in text or "\u2014" in text:
            text.parent.replace(text, nodes.Text(text.replace("\u2013", "-").replace("\u2014", "-")))


def setup(app) -> None:
    app.connect("builder-inited", _copy_notebooks)
    app.connect("doctree-resolved", _short_dashes)
